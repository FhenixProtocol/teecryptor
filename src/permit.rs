    // ---- provider reuse ---------------------------------------------------

    use std::sync::atomic::{AtomicUsize, Ordering};
    use std::sync::Arc;
    use tokio::io::{AsyncReadExt, AsyncWriteExt};
    use tokio::net::TcpListener;

    /// Minimal JSON-RPC mock that (a) counts how many TCP connections it
    /// accepts and (b) answers every `eth_call` with an ABI-encoded `true`
    /// over a keep-alive HTTP/1.1 connection. One connection serving N requests
    /// is exactly what connection reuse looks like on the wire; a fresh provider
    /// per call would instead open N connections. Returns `(url, conn_counter)`.
    async fn spawn_true_rpc() -> (String, Arc<AtomicUsize>) {
        let listener = TcpListener::bind("127.0.0.1:0").await.expect("bind");
        let url = format!("http://{}", listener.local_addr().unwrap());
        let conns = Arc::new(AtomicUsize::new(0));
        let conns_srv = conns.clone();

        tokio::spawn(async move {
            loop {
                let (mut sock, _) = match listener.accept().await {
                    Ok(p) => p,
                    Err(_) => return,
                };
                conns_srv.fetch_add(1, Ordering::SeqCst);
                tokio::spawn(async move {
                    let mut buf = [0u8; 4096];
                    // Serve multiple keep-alive requests on the same connection.
                    loop {
                        let n = match sock.read(&mut buf).await {
                            Ok(0) | Err(_) => return,
                            Ok(n) => n,
                        };
                        // Find the JSON-RPC id so the response correlates.
                        let body = &buf[..n];
                        let text = String::from_utf8_lossy(body);
                        let id = text
                            .split("\"id\":")
                            .nth(1)
                            .and_then(|s| s.split([',', '}']).next())
                            .map(|s| s.trim())
                            .filter(|s| !s.is_empty())
                            .unwrap_or("1")
                            .to_string();
                        // 32-byte ABI-encoded bool `true` (0x00..01).
                        let result = "0x".to_string() + &"00".repeat(31) + "01";
                        let json =
                            format!("{{\"jsonrpc\":\"2.0\",\"id\":{id},\"result\":\"{result}\"}}");
                        let resp = format!(
                            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n\
                             Content-Length: {}\r\nConnection: keep-alive\r\n\r\n{}",
                            json.len(),
                            json
                        );
                        if sock.write_all(resp.as_bytes()).await.is_err() {
                            return;
                        }
                    }
                });
            }
        });
        (url, conns)
    }

    /// A bad rpc_url must fail when the [`ChainConfig`] is built (boot), not
    /// lazily on the first verify call — this is what guarantees the provider
    /// exists pre-built and is reused rather than constructed per request.
    #[test]
    fn bad_rpc_url_fails_at_construction() {
        let err =
            ChainConfig::new("not a url".into(), TEST_TM_ADDR, Duration::from_secs(5)).unwrap_err();
        assert!(matches!(err, AcpError::Misconfigured(_)), "got {err:?}");
    }

    /// The provider is built once at construction and reused across calls:
    /// three sequential `verify_publicly_allowed` calls against one mock RPC
    /// all succeed AND the server accepts exactly **one** TCP connection. With
    /// the old per-call `ProviderBuilder::new().connect_http()` each call would
    /// open its own pool → three cold connections.
    #[tokio::test]
    async fn provider_reused_across_repeated_calls() {
        let (url, conns) = spawn_true_rpc().await;

        let cfg =
            ChainConfig::new(url, TEST_TM_ADDR, Duration::from_secs(5)).expect("valid rpc_url");
        let chains = ChainsVerifierConfig {
            chains: HashMap::from([(TEST_CHAIN_ID, cfg)]),
        };

        let handle = U256::from(1u8);
        for i in 0..3 {
            verify_publicly_allowed(&chains, handle, TEST_CHAIN_ID)
                .await
                .unwrap_or_else(|e| panic!("call {i} should succeed, got {e:?}"));
        }

        assert_eq!(
            conns.load(Ordering::SeqCst),
            1,
            "expected the pooled provider to reuse one connection across 3 calls"
        );
    }
