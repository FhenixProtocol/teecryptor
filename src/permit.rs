//! EIP-712 ACP (Access Control Permission) verification, matching cofhe's
//! `ACPIssuerSelf` shape so the same caller wallets/signatures used against
//! the threshold dispatcher work against Teecryptor unchanged.
//!
//! ACP is cofhe's "Permit V3" (cofhe-contracts#87, merged to `v0.2`). It
//! replaces the V2 `Permission` struct: `validatorId`/`validatorContract`
//! become `revokerData`/`revokerContract`, and three scope fields (`scope`,
//! `contracts`, `handles`) are added. **There is no V2 compatibility path** —
//! an upgraded ACL exposes a different `isAllowedWithPermission` selector and
//! a different EIP-712 domain version, so a V2 permit cannot verify against
//! it (and an ACP cannot verify against a pre-upgrade ACL).
//!
//! Phase 2 verification is **delegated to the on-chain TaskManager** via
//! `isAllowedWithPermission(ACP, handle)` — same authority that cofhe's
//! dispatcher consults. Teecryptor does not re-implement ACL semantics
//! locally: it does not evaluate scopes, does not call the revoker contract,
//! and does not check scope/array consistency. It transports the
//! [`AcpData`] from the caller to the contract and trusts the contract's
//! boolean answer (with bounded timeouts on the RPC call). Local-only EIP-712
//! verification is exposed as a helper for tests / future offline modes.
//!
//! Domain (mirrors `EIP712Upgradeable::__EIP712_init_unchained("ACL","2")`):
//!
//! ```text
//! EIP712Domain { name: "ACL", version: "2", chainId, verifyingContract }
//! ```
//!
//! Note the version is **"2"** for ACP (V2 permits used "1"). The upgraded
//! `PermissionedUpgradeable` overrides `_EIP712Name`/`_EIP712Version` so the
//! domain comes from code rather than from storage written at initialization,
//! which is what lets the ACL be upgraded in place without a migration tx.
//!
//! The verifyingContract is the **ACL** contract address per chain, not
//! TaskManager — see the compatibility doc §6 in the gitops repo. chainId comes from the request
//! (`host_chain_id`).

